"""Compare two or more backtest results — signal layer + portfolio layer."""
from __future__ import annotations

import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from qsys.reports.base import ReportSection, ReportStatus, RunReport, save_report  # noqa: E402


def export_ui_report(
    result: dict[str, Any],
    label: str,
    reports_dir: Path,
) -> str:
    """Export a single backtest result to UI-compatible ``backtest_<run_id>.json``.

    The file lands in ``reports_dir/`` and is automatically picked up by
    ``ResearchCockpitRepository`` — no frontend changes needed.

    Parameters
    ----------
    result : dict
        Backtest result from ``backtest_runner.run_backtest()``.
    label : str
        Human-readable strategy label.
    reports_dir : Path
        Directory where ``backtest_<run_id>.json`` will be written
        (typically ``SysQ/experiments/reports/``).

    Returns
    -------
    str
        The generated ``run_id``.
    """
    reports_dir.mkdir(parents=True, exist_ok=True)

    metrics = result.get("metrics", {})
    equity_curve = result.get("equity_curve")
    trades = result.get("trades")
    score_col = result.get("score_col", "kronos_ret_5d_zscore")

    # Derive a unique run_id from the label so multiple variants don't collide
    label_slug = label.replace("kronos_", "").replace("kronos", "raw")
    run_id = f"alpha_v3_kronos_csi800_{label_slug}"
    model_name = "NeoQuasar/Kronos-small"

    # UI dedup key: different mainline_object_name per variant
    mainline_obj = f"alpha_v3_kronos_{label_slug}"

    # Save daily equity CSV
    daily_csv = reports_dir / f"daily_equity_{run_id}.csv"
    if equity_curve is not None and not equity_curve.empty:
        eq = equity_curve.copy()
        eq = eq.rename(columns={
            "date": "date",
            "equity": "equity",
            "ret": "daily_return",
            "zc_equity": "zero_cost_total_assets",
        })
        eq.to_csv(daily_csv, index=False)
    else:
        # Create minimal equity curve if none available
        pd.DataFrame({"date": [], "equity": [], "daily_return": []}).to_csv(daily_csv, index=False)

    # Save trades CSV
    trades_csv = reports_dir / f"trades_{run_id}.csv"
    if trades is not None and not trades.empty:
        trades.to_csv(trades_csv, index=False)
    else:
        pd.DataFrame({"date": [], "symbol": [], "side": [], "amount": [], "price": [], "fee": []}).to_csv(trades_csv, index=False)

    report = {
        "run_id": run_id,
        "workflow": "backtest",
        "signal_date": str(equity_curve.iloc[0]["date"])[:10] if equity_curve is not None and not equity_curve.empty else "",
        "execution_date": str(equity_curve.iloc[-1]["date"])[:10] if equity_curve is not None and not equity_curve.empty else "",
        "model_info": {
            "model_name": model_name,
            "model_path": model_name,
            "universe": "csi800",
            "feature_set": "kronos_raw_ohlcv",
            "label_type": "kronos_ret_5d",
            "top_k": 20,
            "rebalance_freq": "weekly",
            "mainline_object_name": mainline_obj,
        },
        "notes": [
            f"alpha_v3_kronos_small experiment",
            f"score_col={score_col}",
            f"generated by run_pipeline.py at {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        ],
        "sections": [
            {
                "name": "Performance",
                "status": "success",
                "message": "Alpha V3 Kronos-small zero-shot backtest",
                "metrics": {
                    "total_return": f"{metrics.get('total_ret', 0) * 100:.2f}%",
                    "annual_return": f"{metrics.get('ann_ret', 0) * 100:.2f}%",
                    "sharpe": f"{metrics.get('sharpe', 0):.3f}",
                    "max_drawdown": f"{metrics.get('max_dd', 0) * 100:.2f}%",
                    "calmar": f"{metrics.get('calmar', 0):.3f}",
                    "win_rate": f"{metrics.get('win_rate', 0) * 100:.1f}%",
                    "ann_turnover": f"{metrics.get('ann_to', 0):.1f}x",
                },
            },
        ],
        "artifacts": {
            "daily_result": str(daily_csv.relative_to(reports_dir.parent.parent)),
            "trades": str(trades_csv.relative_to(reports_dir.parent.parent)),
        },
    }

    report_path = reports_dir / f"backtest_{run_id}.json"
    with open(report_path, "w") as f:
        json.dump(report, f, indent=2, default=str)
    print(f"\n[UI] Exported backtest report: {report_path}")
    print(f"  daily: {daily_csv}")
    print(f"  trades: {trades_csv}")
    return run_id


def build_report(
    results: dict[str, dict],
    output_dir: Path,
    run_id: str = "alpha_v3_comparison",
) -> dict[str, Any]:
    """Build a side-by-side comparison report from multiple backtest results.

    Parameters
    ----------
    results : dict[str, dict]
        Mapping of strategy label → backtest result dict (from backtest_runner).
    output_dir : Path
        Output directory for report artifacts.
    run_id : str
        Report run ID.

    Returns
    -------
    dict of report paths and summary metrics.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    # ── Portfolio Layer Comparison ──
    print(f"\n{'='*70}")
    print("Comparison Report — Portfolio Layer")
    print(f"{'='*70}")

    metric_rows = []
    for label, r in results.items():
        m = r.get("metrics", {})
        metric_rows.append({
            "strategy": label,
            "total_return": m.get("total_ret", 0),
            "annual_return": m.get("ann_ret", 0),
            "sharpe": m.get("sharpe", 0),
            "max_drawdown": m.get("max_dd", 0),
            "calmar": m.get("calmar", 0),
            "ann_turnover": m.get("ann_to", 0),
            "total_cost": m.get("cost", 0),
            "win_rate": m.get("win_rate", 0),
            "avg_positions": m.get("avg_pos", 0),
            "n_days": m.get("ndays", 0),
        })
        print(f"  {label}: Ret={m.get('total_ret',0)*100:.2f}%, "
              f"Sharpe={m.get('sharpe',0):.4f}, "
              f"MaxDD={m.get('max_dd',0)*100:.2f}%")

    metrics_df = pd.DataFrame(metric_rows)
    csv_path = output_dir / "backtest_metrics.csv"
    metrics_df.to_csv(csv_path, index=False)
    print(f"  → {csv_path}")

    # ── Equity Curves Overlay ──
    eq_data = {}
    for label, r in results.items():
        curve = r.get("equity_curve")
        if curve is not None and not curve.empty:
            date_col = "date" if "date" in curve.columns else curve.columns[0]
            eq_data[label] = curve.set_index(date_col)["equity"]

    if eq_data:
        combined = pd.DataFrame(eq_data)
        parquet_path = output_dir / "portfolio_curves.parquet"
        combined.to_parquet(parquet_path)
        print(f"  → {parquet_path}")

    # ── Signal Layer Comparison ──
    print(f"\n{'='*70}")
    print("Comparison Report — Signal Layer")
    print(f"{'='*70}")

    # ── Markdown Report ──
    md_path = output_dir / "alpha_v3_vs_alpha_v1_report.md"
    with open(md_path, "w") as f:
        f.write(f"# Alpha V3 Comparison Report\n\n")
        f.write(f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")
        f.write("## Portfolio Performance\n\n")
        f.write("| Strategy | Total Ret | Ann Ret | Sharpe | Max DD | Calmar | WinRate | TO |\n")
        f.write("|----------|-----------|---------|--------|--------|--------|---------|------|\n")
        for _, row in metrics_df.iterrows():
            f.write(
                f"| {row['strategy']} | {row['total_return']*100:.2f}% | "
                f"{row['annual_return']*100:.2f}% | {row['sharpe']:.4f} | "
                f"{row['max_drawdown']*100:.2f}% | {row['calmar']:.4f} | "
                f"{row['win_rate']*100:.1f}% | {row['ann_turnover']:.1f}x |\n"
            )
        f.write("\n## Notes\n\n")
        for label in results:
            r = results[label]
            if label == "alpha_v1":
                f.write(f"- **{label}**: LightGBM baseline (rolling retrain per window)\n")
            else:
                f.write(f"- **{label}**: Kronos-small zero-shot signal\n")

    print(f"  → {md_path}")

    # ── RunReport ──
    report = RunReport(
        workflow="backtest_comparison",
        run_id=run_id,
        signal_date=datetime.now().strftime("%Y-%m-%d"),
        execution_date=datetime.now().strftime("%Y-%m-%d"),
        status=ReportStatus.SUCCESS,
        sections=[
            ReportSection(
                name="Portfolio Comparison",
                status=ReportStatus.SUCCESS,
                metrics={
                    row["strategy"]: {
                        "total_return": f"{row['total_return']*100:.2f}%",
                        "sharpe": f"{row['sharpe']:.4f}",
                        "max_drawdown": f"{row['max_drawdown']*100:.2f}%",
                    }
                    for _, row in metrics_df.iterrows()
                },
            ),
        ],
    )
    report_path = output_dir / "report.json"
    saved = save_report(report, output_dir=str(output_dir))
    print(f"  → {saved}")

    # ── Manifest ──
    manifest = {
        "run_id": run_id,
        "created_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "strategies": list(results.keys()),
        "artifacts": {
            "metrics_csv": str(csv_path),
            "equity_curves": str(parquet_path) if eq_data else None,
            "report_md": str(md_path),
        },
    }
    manifest_path = output_dir / "manifest.json"
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2, default=str)

    print(f"  → {manifest_path}")
    return manifest
